export interface Variant {
  id: string
  SKU: string
  size: string
  flavor?: string
  price: number
  compareAtPrice?: number
  available: boolean
}
export interface ProductSource {
  name: string
  url: string
  capturedAt: string
  imageUrls: string[]
}
export interface Product {
  id: string
  handle: string
  title: string
  brandId: string
  categoryId: string
  description: string
  images: string[]
  tags: string[]
  basePrice: number
  compareAtPrice?: number
  currency: 'INR'
  featured: boolean
  bestseller: boolean
  variants: Variant[]
  source: ProductSource
  rating: { value: number; count: number; scale: number } | null
}
export interface Brand {
  id: string
  name: string
  short: string
  color: string
  logo: string
  logoAspect: number
}
export interface Category {
  id: string
  name: string
  handle: string
  tagline: string
}
// Generated by scripts/import-catalog.py; see SOURCES.md.
export const brands: Brand[] = catalog.brands
export const categories: Category[] = catalog.categories
export const products = catalog.products as Product[]
export const hero: { src: string; productId: string; alt: string }[] = catalog.hero
export const findProduct = (id: string) => products.find((p) => p.id === id)
// A representative product photo for each category tile: its featured product.
export const categoryProduct = (categoryId: string) =>
  products.find((p) => p.categoryId === categoryId && p.featured) ??
  products.find((p) => p.categoryId === categoryId)!
export const money = (paise: number) =>
  new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    maximumFractionDigits: paise % 100 ? 2 : 0,
  }).format(paise / 100)
